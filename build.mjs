/**
 * Build lib/client.js — the single self-contained browser bundle DSH serves.
 *
 * The output uses DSH's client module wrapper:
 *   window.__ModuleLoader__.load({ id, factory: (require) => module })
 *
 * The vendored opencc-js UMD build is inlined and forced down its global branch
 * (module/exports/define are shadowed to undefined) so its payload never leaks
 * into this module's own exports.
 */
import { mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = dirname(fileURLToPath(import.meta.url))
const read = (relative) => readFileSync(join(root, relative), 'utf8')
const pkg = JSON.parse(read('package.json'))

/** Strip ESM syntax so the module bodies can be concatenated into one scope. */
function inlineModule(relative) {
  return read(relative)
    .replace(/^import\s[^\n]*\n/gm, '')
    .replace(/^export\s*\{[\s\S]*?\}\s*;?[ \t]*\r?\n?/gm, '')
    .replace(/^export\s+/gm, '')
    .trimEnd()
}

const vendor = read('src/vendor/opencc.full.umd.js')
const vendorBlock = [
  '//#region vendored opencc-js (MIT; OpenCC dictionaries)',
  'var OpenCC = (function () {',
  'var module, exports, define; // shadowed so the UMD takes its global branch',
  'var previous = globalThis.OpenCC;',
  vendor,
  'var captured = globalThis.OpenCC;',
  'try { globalThis.OpenCC = previous; } catch (error) { /* ignore */ }',
  'return captured;',
  '})();',
  '//#endregion',
].join('\n')

const output = [
  `// ${pkg.name} v${pkg.version} — generated by build.mjs; do not edit by hand.`,
  'window.__ModuleLoader__.load({',
  `\tid: ${JSON.stringify(pkg.name)},`,
  '\tfactory: (require) => {',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  "\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });",
  '',
  vendorBlock,
  '',
  inlineModule('src/convert.mjs'),
  '',
  inlineModule('src/dom-convert.mjs'),
  '',
  inlineModule('src/apply.mjs').replaceAll('__DSH_ZH_TW_UI_VERSION__', pkg.version),
  '',
  '\t\texports.apply = apply;',
  '\t\texports.inject = inject;',
  '\t\treturn module.exports;',
  '\t},',
  '});',
  '',
].join('\n')

mkdirSync(join(root, 'lib'), { recursive: true })
const target = join(root, 'lib', 'client.js')
// Compile before writing: a broken bundle must never reach the profile.
try {
  new vm.Script(output, { filename: target })
} catch (error) {
  console.error(`generated bundle is not valid JavaScript: ${error.message}`)
  process.exit(1)
}
writeFileSync(target, output)
console.log(`wrote ${target} (${statSync(target).size} bytes, opencc ${vendor.length} chars)`)
